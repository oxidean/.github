#!/bin/sh
# commit-check — commit-message gate for .github.
#
# Two contracts, enforced on every surface (hook, CI, ad-hoc):
#
#   1. SemVer-prefix grammar on the subject line (same shape as the
#      oxidean monorepo's conventional-commit contract):
#          type(scope)?(!)? ": " subject
#      types: feat fix perf revert docs chore test style refactor build ci
#      exempt: "Merge ...", "Revert \"...\"", "chore(release): ..."
#
#   2. No AI/tool attribution or markers anywhere in the message
#      (.cursor/rules/no-ai-attribution.mdc): no AI Co-Authored-By /
#      Generated-with / Made-with trailers, no bot signatures, no
#      zero-width or invisible markers. Human co-authors and
#      Signed-off-by stay welcome.
#
# Usage:
#   commit-check.sh --file <msgfile>     commit-msg hook entry point
#   commit-check.sh --message "<msg>"    lint one message
#   commit-check.sh --pr-title "<t>"     lint a PR title
#   commit-check.sh --range A..B         lint every commit in a range
#   commit-check.sh --scan-file <f>      attribution scan only (PR body)
#
# Exit 0 clean, 1 on any violation. Warnings print but do not fail.
set -eu

TYPES='feat|fix|perf|revert|docs|chore|test|style|refactor|build|ci'
SUBJECT_WARN=100
fail=0

err() { printf '%s\n' "commit-check: $*" >&2; fail=1; }
warn() { printf '%s\n' "commit-check: warning: $*" >&2; }

# --- attribution scan: whole message text -----------------------------

check_attribution() {
    _msg=$1
    # One vendor alternation shared by every pattern below — extend it
    # here, never in a single rule, or the rules drift apart.
    _VENDOR='claude|cursor|copilot|chatgpt|codex|gemini|devin|openai|anthropic|codeium|windsurf|github[[:space:]]+copilot|claude[[:space:]]+code|(claude|gemini)[[:space:]]+(opus|sonnet|pro|ultra)|swe-[0-9a-z.-]*' 
    # AI co-author / bot trailers. A human Co-authored-by is fine; the
    # ban is on AI vendors, bots, and *-ai-* / [bot] addresses.
    _co=$(printf '%s\n' "$_msg" | grep -iE '^[[:space:]]*co-?authored-by:' || :)
    # Unambiguous machine signals anywhere in the trailer: [bot] tags,
    # bot@ addresses, *-ai-integration logins, AI-vendor domains (literal
    # list of vendor-owned domains — never github.com, or humans on the
    # privacy relay get flagged), and a vendor token inside a bare email
    # (no <display name>) — bot forms like
    # "Co-authored-by: 175728472+Copilot@users.noreply.github.com".
    if printf '%s\n' "$_co" | grep -qiE '\[bot\]|(^|[<.[:space:]_+-])bot@|ai-integration|noreply@(anthropic|openai)\.|@(anthropic|openai|cognition|devin|codeium|windsurf|claude-code|cursor|gemini|chatgpt|codex|copilot)\.(com|ai|dev|io)([[:space:]>]|$)|:[[:space:]]*[^<[:space:]]*('"$_VENDOR"')[^<[:space:]]*@|[a-z0-9._+-]*(ai[-_.](agent|assistant)|(agent|assistant)[-_.]ai)([._+-][a-z0-9]+|[0-9]+)*@'; then
        err "AI Co-authored-by trailer"
    # A bare vendor identity as the display name — "Co-authored-by:
    # Claude <noreply@anthropic.com>" hits the domain rule above; this
    # catches no-email and generic-mailbox forms. Human names that merely
    # CONTAIN a vendor token ("Claude Martin <claude.martin@…>") stay
    # legal per .cursor/rules/no-ai-attribution.mdc.
    elif printf '%s\n' "$_co" | sed 's/^[^:]*:[[:space:]]*//; s/<.*//' \
        | grep -qiE '^\[?('"$_VENDOR"')\]?(\([^)]*\))?([[:space:]-]?ai)?[[:space:]]*$'; then
        err "AI Co-authored-by trailer"
    fi
    # generator footers: "Generated with <tool>", "Made with: X",
    # "Authored via X" — the tool names that sign output, plus the
    # trailer forms regardless of vendor.
    # connector may carry a colon ("Created with: Cursor"); the vendor
    # token needs a non-alnum tail so "generated by cursors" stays clean.
    if printf '%s\n' "$_msg" | grep -iqE '(generated|made|created|authored|written|produced)[[:space:]]+(with|by|via):?[[:space:]]*\[?[[:space:]]*('"$_VENDOR"')([^a-z0-9]|$)'; then
        err "AI generator footer"
    fi
    if printf '%s\n' "$_msg" | grep -iqE '^[[:space:]]*(generated|made|authored)[- ](with|by|via)[[:space:]]*:'; then
        err "generator trailer"
    fi
    # standalone "via <tool>" / "by <tool>" / "with <tool>" lines — the
    # footer regex above needs a leading verb, so a lone via-line slips.
    # "via"/"by" are attribution verbs — trailing context still flags.
    # "with"/"using" open ordinary sentences too, so they only count as
    # a signature when the tool name closes out the line.
    if printf '%s\n' "$_msg" | grep -qiE '^[[:space:]]*(via|by)[[:space:]]+\[?('"$_VENDOR"')\]?(\([^)]*\))?([[:space:]-]?ai)?([^a-z0-9]|$)|^[[:space:]]*(with|using)[[:space:]]+\[?('"$_VENDOR"')\]?(\([^)]*\))?([[:space:]-]?ai)?[[:space:].!,;:()]*$'; then
        err "attribution via-line"
    fi
    # bot-emoji signature: a bare 🤖 line, or 🤖 sharing a line with
    # attribution vocabulary — a mid-sentence robot mention stays clean.
    _bot=$(printf '%s\n' "$_msg" | grep '🤖' || :)
    if printf '%s\n' "$_bot" | grep -qiE '^[[:space:]]*🤖[[:space:]]*$|generated|made|created|authored|written|produced|built|co-?authored|via[[:space:]]|with[[:space:]]|by[[:space:]]'; then
        err "bot-emoji attribution marker"
    fi
    # AI named as the author/agent — not as the subject of the change.
    # (kept narrow on purpose: "add Copilot webhook" must stay legal)
    if printf '%s\n' "$_msg" | grep -iqE '\b(as an ai|i generated this|authored by \[?('"$_VENDOR"'))\b'; then
        err "AI self-attribution"
    fi
    # vendor-stamped HTML comments smuggled into the message
    if printf '%s\n' "$_msg" | grep -iqE '<!--[^>]*('"$_VENDOR"'|generated|made|created|authored|written|produced|built|powered|co-?authored|attributed|🤖)[^>]*'; then
        err "attribution HTML comment"
    fi
    # zero-width / invisible markers: U+200B..D, U+2060, U+FEFF as raw
    # UTF-8 byte sequences — byte grep, no -P dependency
    if printf '%s\n' "$_msg" | LC_ALL=C grep -q \
        -e "$(printf '\342\200\213')" -e "$(printf '\342\200\214')" \
        -e "$(printf '\342\200\215')" -e "$(printf '\342\201\240')" \
        -e "$(printf '\357\273\277')"; then
        err "zero-width/invisible attribution marker"
    fi
}

# --- grammar: subject line only ---------------------------------------

check_subject() {
    _subject=$1
    _where=${2:-subject}
    # exempt shapes: merges, reverts, release tooling commits
    case "$_subject" in
        "Merge "*|"Revert \""*|"chore(release):"*) return 0 ;;
    esac
    if ! printf '%s\n' "$_subject" | grep -qE '^[A-Za-z]+(\([^)]+\))?!?: +[^ ]'; then
        err "$_where does not match \"type(scope)!: subject\": ${_subject}"
        return
    fi
    _type=$(printf '%s\n' "$_subject" | sed -E 's/^([A-Za-z]+).*/\1/')
    if ! printf '%s\n' "$_type" | grep -qxE "$TYPES"; then
        err "$_where uses unknown type \"$_type\" (allowed: $(printf '%s' "$TYPES" | tr '|' ' '))"
    fi
    if [ "${#_subject}" -gt "$SUBJECT_WARN" ]; then
        warn "$_where is ${#_subject} chars (> $SUBJECT_WARN)"
    fi
}

check_message() {
    _msg=$1
    _where=${2:-subject}
    check_subject "$(printf '%s\n' "$_msg" | head -1)" "$_where"
    check_attribution "$_msg"
}

# --- modes -------------------------------------------------------------

case "${1:-}" in
    --file)
        [ -f "${2:-}" ] || { err "--file needs a readable message file"; exit 1; }
        # COMMIT_EDITMSG carries comment lines, and `git commit -v`
        # appends the staged diff below the scissors marker. Grammar
        # sees the cleaned message (comments + scissors cut, honoring
        # core.commentString/commentChar). Attribution scans everything BEFORE the
        # scissors line including `#`-lines: `git commit -m` keeps them
        # in history, so a marker hidden in one must fail here exactly
        # as it would in CI — while diff content past the marker is not
        # part of the message and is left alone.
        # commentString (Git >= 2.45) wins over commentChar and may be
        # multi-char; commentChar itself keeps only its first byte,
        # empty|auto means '#'.
        _cc=$(git config --get core.commentString 2>/dev/null || :)
        if [ -z "$_cc" ]; then
            _cc=$(git config --get core.commentChar 2>/dev/null || :)
            case "$_cc" in ''|auto) _cc='#' ;; *) _cc=${_cc%"${_cc#?}"} ;; esac
        fi
        # the scissors line is the whole line "<cs> ---- >8 ----": a line
        # merely starting with it is message text, not a cut. The marker
        # goes via ENVIRON — `awk -v` would mangle a backslash comment
        # string through its escape processing.
        _precut=$(MARKER="$_cc ------------------------ >8 ------------------------" \
            awk 'BEGIN{m=ENVIRON["MARKER"]} $0 == m {exit} {print}' "$2")
        _cleaned=$(printf '%s\n' "$_precut" | git stripspace --strip-comments)
        check_subject "$(printf '%s\n' "$_cleaned" | head -1)" "subject"
        check_attribution "$_precut"
        ;;
    --message)
        check_message "${2:-}" "subject"
        ;;
    --pr-title)
        check_message "${2:-}" "PR title"
        ;;
    --scan-file)
        [ -f "${2:-}" ] || { err "--scan-file needs a readable file"; exit 1; }
        check_attribution "$(cat "$2")"
        ;;
    --range)
        _range=${2:-}
        [ -n "$_range" ] || { err "--range needs A..B"; exit 1; }
        # resolve first: `set -e` does not reach a command substitution
        # in a `for` word list, so a bad range would silently lint zero
        # commits (post-force-push before-SHAs go unreachable).
        _shas=$(git rev-list "$_range") || { err "cannot resolve range $_range"; exit 1; }
        [ -n "$_shas" ] || { err "empty range $_range"; exit 1; }
        for _sha in $_shas; do
            _msg=$(git log -1 --format=%B "$_sha")
            _before=$fail
            check_message "$_msg" "commit ${_sha}"
            [ "$fail" = "$_before" ] || printf '%s\n' "  ^^ in range $_range" >&2
        done
        ;;
    *)
        sed -n '2,33p' "$0" >&2
        exit 2
        ;;
esac
exit "$fail"
